// Generate the classic browser bundle so index.html works from file:// as well as GitHub Pages.
import { readFile, writeFile } from 'node:fs/promises';

const sourceFiles = ['model.js', 'history.js', 'chart.js', 'app.js'];
const parts = [];
for (const file of sourceFiles) {
  const source = await readFile(new URL(file, import.meta.url), 'utf8');
  const withoutImports = source.replace(/^import\s+[^;]+;\s*$/gm, '');
  const classic = withoutImports.replace(/^export\s+(?=(?:class|function|const|let|var)\b)/gm, '');
  if (/^\s*(?:import|export)\s/m.test(classic)) throw new Error(`Unsupported module syntax in ${file}`);
  parts.push(`// ---- ${file} ----\n${classic.trim()}`);
}
const output = `// Generated by build.mjs. Edit the source modules, then run npm run build.\n(() => {\n'use strict';\n${parts.join('\n\n')}\n})();\n`;
const path = new URL('playground.bundle.js', import.meta.url);
if (process.argv.includes('--check')) {
  const actual = await readFile(path, 'utf8').catch(() => '');
  if (actual !== output) throw new Error('playground.bundle.js is stale. Run npm run build.');
} else {
  await writeFile(path, output, 'utf8');
  console.log('Generated playground.bundle.js');
}
